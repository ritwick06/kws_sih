MEL = tf.signal.linear_to_mel_weight_matrix(40, 257, SR, 80.0, 7600.0)
def mfcc_raw(wav):                                          # (B, 32000) -> (B, 99, 20), un-normalised
    s = tf.signal.stft(wav, 480, 320, 512, window_fn=tf.signal.hann_window, pad_end=False)
    mel = tf.matmul(tf.abs(s)**2, MEL)
    return tf.signal.mfccs_from_log_mel_spectrograms(tf.math.log(mel + 1e-6))[..., :20]
def mfcc_np(W, bs=1024):
    return np.concatenate([mfcc_raw(tf.constant(W[i:i+bs])).numpy() for i in range(0, len(W), bs)])
