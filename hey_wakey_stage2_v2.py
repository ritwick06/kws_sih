def tds_block(x, ch, dil, fs, name):
    x = L.DepthwiseConv2D((5, 3), padding="same", dilation_rate=(dil, 1), use_bias=False, name=f"{name}_dw")(x)
    x = L.Conv2D(ch, 1, strides=(1, fs), use_bias=False, name=f"{name}_pw")(x)      # frequency stride lives in the pointwise conv
    x = L.BatchNormalization(name=f"{name}_bn")(x)
    return L.ReLU(6.0, name=name)(x)

def build_backbone():
    inp = L.Input((99, 20, 1), name="mfcc")
    x = L.Conv2D(24, (5, 3), padding="same", use_bias=False, name="stem_conv")(inp)
    x = L.ReLU(6.0, name="stem")(L.BatchNormalization(name="stem_bn")(x))
    for name, ch, dil, fs in [("tds1", 32, 1, 2), ("tds2", 40, 2, 2), ("tds3", 48, 4, 1), ("tds4", 56, 8, 1), ("tds5", 64, 16, 1)]:
        x = tds_block(x, ch, dil, fs, name)
    return tf.keras.Model(inp, x, name="backbone")           # output (99, 5, 64)

def shift_feat(Xb, rs, SIL):                                  # +-20 frame shift, silence fill
    out = np.empty_like(Xb)
    for i in range(len(Xb)):
        s = int(rs.integers(-20, 21)); o = np.broadcast_to(SIL, (99, 20)).copy()
        if s >= 0: o[s:] = Xb[i][:99 - s]
        else:      o[:99 + s] = Xb[i][-s:]
        out[i] = o
    return out

def stage_a(bb, D, SIL, epochs=30, steps=150, bs=128):
    x = L.Dropout(0.2)(L.GlobalAveragePooling2D()(bb.output)); clf = tf.keras.Model(bb.input, L.Dense(25)(x))
    tr, va = D["split"] == "train", D["split"] == "trainA_val"
    Xtr, ytr, Xva, yva = D["X"][tr], D["y"][tr], D["X"][va][..., None], D["y"][va]
    clf.compile(tf.keras.optimizers.Adam(tf.keras.optimizers.schedules.CosineDecay(2e-3, epochs*steps)),
                tf.keras.losses.SparseCategoricalCrossentropy(from_logits=True), metrics=["accuracy"])
    byc = [np.where(ytr == c)[0] for c in range(25)]; rs = np.random.default_rng(SEED); best = (0, None)
    for ep in range(epochs):
        for _ in range(steps):                                # class-balanced sampling
            idx = np.array([rs.choice(byc[c]) for c in rs.integers(0, 25, bs)])
            clf.train_on_batch(shift_feat(Xtr[idx], rs, SIL)[..., None], ytr[idx])
        loss, acc = clf.evaluate(Xva, yva, verbose=0, batch_size=512)
        print(f"A ep{ep+1:02d} held-out-speaker val acc {acc:.4f}");
        if acc > best[0]: best = (acc, clf.get_weights())
    clf.set_weights(best[1]); return best[0]

def stage_b(bb, D, SIL, epochs=40, eps=40, lr=5e-4, T=0.10):
    metric = tf.keras.Model(bb.input, L.UnitNormalization()(L.Dense(32, name="proj")(L.GlobalAveragePooling2D()(bb.output))), name="metric_encoder")
    opt = tf.keras.optimizers.Adam(lr); rs = np.random.default_rng(SEED + 1)
    def pools(split, nw):
        m = D["split"] == split; X, y = D["X"][m], D["y"][m]; return X, {w: np.where(y == w)[0] for w in range(nw)}
    Xt, Pt = pools("train", 25); Xv, Pv = pools("val", 5); Xs, Ps = pools("test", 5)
    def episode(X, P, nw, shift):
        ws = rs.choice(nw, 5, replace=False); x = np.stack([X[rs.choice(P[w], 10, replace=False)] for w in ws])   # 5 words x (5 support + 5 query)
        if shift: x = shift_feat(x.reshape(-1, 99, 20), rs, SIL).reshape(5, 10, 99, 20)
        return tf.constant(x[..., None], tf.float32)
    def fwd(x):
        e = tf.reshape(metric(tf.reshape(x, (-1, 99, 20, 1)), training=False), (5, 10, 32))   # BN uses stage-A statistics
        proto = tf.math.l2_normalize(tf.reduce_mean(e[:, :5], 1), -1); q = tf.reshape(e[:, 5:], (-1, 32))
        logits = tf.matmul(q, proto, transpose_b=True) / T; yq = tf.repeat(tf.range(5), 5)
        loss = tf.reduce_mean(tf.keras.losses.sparse_categorical_crossentropy(yq, logits, from_logits=True))
        return loss, tf.reduce_mean(tf.cast(tf.argmax(logits, 1) == tf.cast(yq, tf.int64), tf.float32))
    @tf.function
    def step(x):
        with tf.GradientTape() as tape: loss, acc = fwd(x)
        opt.apply_gradients(zip(tape.gradient(loss, metric.trainable_variables), metric.trainable_variables)); return loss, acc
    ev = tf.function(fwd); best = (0, None)
    for ep in range(epochs):
        for _ in range(eps): step(episode(Xt, Pt, 25, True))
        va = float(np.mean([ev(episode(Xv, Pv, 5, False))[1].numpy() for _ in range(30)]))
        print(f"B ep{ep+1:02d} unseen-word val acc {va:.4f}")
        if va > best[0]: best = (va, metric.get_weights())
    metric.set_weights(best[1])
    te = [ev(episode(Xs, Ps, 5, False))[1].numpy() for _ in range(200)]                 # opened once
    return metric, best[0], float(np.mean(te)), float(np.std(te))

