"""## 6. Models and evaluation helpers"""

def make_head():
    i = L.Input((99, 64)); x = L.Normalization(axis=-1, name="norm")(i)
    x = L.SpatialDropout1D(0.2)(L.Conv1D(48, 5, padding="same", activation="relu")(x))
    x = L.SpatialDropout1D(0.2)(L.Conv1D(32, 5, padding="same", dilation_rate=2, activation="relu")(x))
    x = L.Dropout(0.3)(L.Concatenate()([L.GlobalMaxPooling1D()(x), L.GlobalAveragePooling1D()(x)]))
    return tf.keras.Model(i, L.Dense(1, activation="sigmoid", kernel_regularizer=tf.keras.regularizers.l2(1e-3))(x))

def get_train(spks, mode):
    allowed = {"clean": [0], "aug": [0, 1], "aug+splice": [0, 1, 2]}[mode]
    m = (M.spk.isin(spks) & M.spk2.isin(spks) & M.aug.isin(allowed)).values       # splices need BOTH source speakers in the training set
    c = M.cls.values[m]; return X[m], (c == 0).astype("float32"), c

def weights(c, hard_w):
    w = np.where(c == 1, hard_w, 1.0).astype("float32"); w[c == 0] *= w[c != 0].sum() / (c == 0).sum(); return w   # balance pos vs neg

def train_head(Xt, yt, ct, epochs=25, hard_w=2.0, seed=SEED):
    tf.random.set_seed(seed); m = make_head(); m.get_layer("norm").adapt(Xt[::4].astype("float32"))
    steps = epochs * int(np.ceil(len(Xt) / 128))
    m.compile(tf.keras.optimizers.Adam(tf.keras.optimizers.schedules.CosineDecay(1e-3, steps)), "binary_crossentropy")
    m.fit(Xt.astype("float32"), yt, sample_weight=weights(ct, hard_w), batch_size=128, epochs=epochs, verbose=0); return m

def train_linear(Xt, yt, ct, C=0.3, hard_w=1.5):                       # the old frozen-adapter recipe
    return LogisticRegression(C=C, max_iter=2000).fit(Xt.astype("float32").mean(1), yt, sample_weight=weights(ct, hard_w))

def score(m, Xe):
    return m.predict_proba(Xe.astype("float32").mean(1))[:, 1] if isinstance(m, LogisticRegression) else m.predict(Xe.astype("float32"), batch_size=256, verbose=0)[:, 0]

def report(s, c, recall=0.95, thr=None):
    pos = s[c == 0]; thr = np.quantile(pos, 1 - recall) if thr is None else thr
    o = dict(auc=roc_auc_score(c == 0, s), thr=float(thr), recall=float((pos >= thr).mean()))
    for k, n in [(1, "hard_FA"), (2, "speech_FA"), (3, "noise_FA")]: o[n] = float((s[c == k] >= thr).mean())
    return o

