def synth_noise(r):
    w = r.standard_normal(N).astype("float32")
    if r.random() < 0.5: w = np.cumsum(w); w -= w.mean()
    return w
def get_noise(r):
    u = r.random()
    if u < 0.4 and BG: b = BG[r.integers(len(BG))]; o = r.integers(0, len(b) - N); return b[o:o+N]
    if u < 0.8 and NS: return np.roll(NS[r.integers(len(NS))], int(r.integers(N)))
    return synth_noise(r)

def place(x, reg, r):                                   # shift while keeping the speech region inside the window
    lim = int(0.5*SR)
    if reg is None: lo, hi = -lim, lim
    else:
        m = int(0.05*SR); lo, hi = -(reg[0]*HOP - m), N - (reg[1]*HOP + m)
        lo, hi = max(min(lo, 0), -lim), min(max(hi, 0), lim)
    s = int(r.integers(lo, hi + 1)); o = np.zeros(N, np.float32)
    if s >= 0: o[s:] = x[:N - s]
    else:      o[:N + s] = x[-s:]
    return o

def augment(w, r, reg, do_shift=True):
    x, ref = w.copy(), rms(w)
    if r.random() < 0.6:                                # speed / pitch
        f = float(r.choice([0.9, 0.95, 1.05, 1.1])); x = resample_poly(x, 100, int(round(f*100))).astype("float32")
        x = np.pad(x, (0, max(0, N - len(x))))[:N]; reg = find_region(x)
    if do_shift: x = place(x, reg, r)
    if r.random() < 0.4:                                # synthetic reverb
        Lr = int(r.uniform(0.08, 0.4)*SR); t = np.arange(Lr)/SR
        ir = r.standard_normal(Lr) * np.exp(-t * r.uniform(8, 30)); ir[0] = 1.0
        x = fftconvolve(x, ir.astype("float32"))[:N].astype("float32"); x *= ref / (rms(x) + 1e-9)
    x = x * 10 ** (r.uniform(-12, 6) / 20)
    if r.random() < 0.7:                                # additive noise, SNR 5-25 dB
        n = get_noise(r); x = x + n * (rms(x) / (rms(n) * 10 ** (r.uniform(5, 25) / 20) + 1e-9))
    return (x / max(1.0, np.abs(x).max() / 0.99)).astype("float32")

