def load_wav(p):
    w, sr = sf.read(p, dtype="float32"); assert sr == SR, (p, sr)
    return w.mean(1) if w.ndim > 1 else w
def fix_len(w): return np.pad(w, (0, max(0, N - len(w))))[:N]

def envelope(w):                                   # mean |x| per 20 ms frame
    n = len(w)//HOP; return np.abs(w[:n*HOP]).reshape(n, HOP).mean(1)
def smooth(e, k): return np.convolve(e, np.ones(k)/k, mode="same")
def find_region(w):
    e = smooth(envelope(w), 3); pk = e.max()
    if pk < 1e-4: return None
    idx = np.where(e > max(3*np.percentile(e, 20), 0.12*pk))[0]
    return (int(idx[0]), int(idx[-1]) + 1) if len(idx) else None
def find_valley(w, reg):                           # dip between the 'hey' lobe and the 'wakey' lobe
    if reg is None or reg[1] - reg[0] < 20: return None
    a, b = reg; e = smooth(envelope(w), 5)
    lo, hi = a + int(0.2*(b-a)), a + int(0.75*(b-a))
    if hi <= lo: return None
    v = lo + int(np.argmin(e[lo:hi])); lobes = min(e[a:v].max(), e[v:b].max())
    return v if lobes > 0 and e[v] < 0.5*lobes else None

